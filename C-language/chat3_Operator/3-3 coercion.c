//强制转换：如果把取值范围大的，赋值给取值范围小的，就需要进行强制转换(相当于隐式转换逆过程)
//弊端：如果被强制转换的数据其值所占的比特大小超过了目标数据类型的内存，那么就会导致数据错误
#include<stdio.h>

int main()
{
    //格式:目标数据类型+变量名 = (目标数据类型) + 被强转的数据
    //注意:不写(目标数据类型)也可以正常输出(因为底层已经进行强制转换),但为了代码可阅读性,所以最好手动书写
    int a = 10;
    short b = (short)a;
    printf("%d\n", b);
    printf("%zu\n", sizeof(b));
    printf("------------------------\n");

    short c =20;
    short d = (short)(b+c);
    printf("%d\n", d);
    printf("%zu\n", sizeof(d));

    return 0;
}