/*
二叉树(Binary Tree)：
一、定义：
    1.二叉树​是每个节点最多只有两个子节点的树结构。这两个子节点通常被称为左子节点​和右子节点。

    2.形式化定义：二叉树是n(n ≥ 0)个节点的有限集合。它要么是空集(空二叉树)，要么由一个根节点和两个
            互不相交的、分别称为左子树和右子树的二叉树组成。


二、基本概念(二叉树特有)：
    1.左孩子/左子树​：一个节点的左分支，其本身也是一棵二叉树。
    2.右孩子/右子树​：一个节点的右分支，其本身也是一棵二叉树。
    3.遍历​：系统地访问树中每个节点一次且仅一次。主要方式有：前序（根左右）、中序（左根右）、
            后序（左右根）、层序（逐层从左到右）。

        
三、二叉树的特点:
    1.结构简单，基础性强：最多两个分支，易于用指针（left, right）或数组实现。
    2.有序性：左右子树是严格区分的，即使结构相同，左右互换后也是不同的二叉树。这为二叉搜索树等
            有序结构提供了基础。
    3.极强的递归性：定义和操作（遍历、求深度等）都天然适合用递归实现，代码简洁。
    4.是许多复杂结构的原型：堆、字典树、线段树等都可以看作二叉树或其变体。
    5.奇偶性：偶数个节点的二叉树必然有偶数个度数为1的节点。


四、二叉树的重要性质(其中1、2、3是树的性质2、3、1的特例)：
    1.第i层上的最大节点数：在二叉树的第i层上至多有2^(i−1)个节点(i ≥ 1)。

    2.高度为h的二叉树的最大节点数：至多有2^h − 1个节点(h ≥ 1)（即满二叉树的情况）。

    3.对任何非空二叉树，如果叶子节点数为n0，度为2的节点数为n2，则满足：n0 = n2 + 1。
        解释：设节点总数为n，度为1的节点数为n1，则有n = n0 + n1 + n2。同时再由树的性质1可得：
            n = n1 + 2 * n2 + 1，两式联立可得结果。

    4.满二叉树的数组存储：对于有n个节点的满二叉树，按层序遍历从1开始编号，则对任意节点i，有：
        (1)其父节点编号为：floor(i/2) (i>1)，其中floor函数表示向下取整。
        (2)当i是非叶子节点：其左孩子的编号为2i，右孩子为2i+1。(证明见最下面单开的部分)。
        (3)当i是叶子节点：2^(h-1) ≤ i ≤ n=2^h - 1 (其中h是满二叉树的高度)。

    5.完全二叉树的数组存储：对于有n个节点的完全二叉树，按层序遍历从1开始编号，则对任意节点i，有：
        (1)其父节点编号为：floor(i/2) (i>1)，其中floor函数表示向下取整。
        (2)其左孩子编号为：2*i (若 2*i ≤ n)。
        (3)其右孩子编号为：2*i + 1 (若 2*i + 1 ≤ n)。
        此性质使得完全二叉树可以高效地用数组存储，而无需指针。


五、特殊二叉树：
    1.满二叉树​：除叶子节点外，每个节点都有两个子节点，且所有叶子节点都在同一层。是“最饱满”的二叉树。
        特点：
        (1)所有叶子节点只能出现在最后一层。
        (2)对于同样深度的二叉树，满二叉树结点数最多，叶子节点数也最多。

    2.完全二叉树​：除最后一层外，其余层都是满的，并且最后一层的节点都靠左排列。这是堆结构的基础。
        特点：
        (1)没有左子树，不能有右子树，上一层没铺满，不能有下一层。
        (2)叶子节点只可能出现在层次最大的两层上。
        (3)完全二叉树只可能有一个度为1的节点。
        (4)对任一节点，若其右分支下的子孙最大层次为h，则其左分支下的子孙的最大层次必为h或h+1。

    3.二叉搜索树​：一种有序二叉树，对于任意节点，其左子树上所有节点的值均小于它，其右子树上所有节点
            的值均大于它。

    4.平衡二叉树​：如AVL树、红黑树，其左右子树的高度差被严格控制，以保证查询效率。


六、二叉树的作用与应用场景：
    1.高效搜索​：使用二叉搜索树​：
        利用有序性，平均时间复杂度为 O(log n)，用于实现集合、映射等数据结构。

    2.排序​：使用堆（完全二叉树）：
        堆排序利用大顶堆/小顶堆的性质，是一种高效的原地排序算法。

    3.优先队列​：使用堆：​
        能快速获取最大/最小元素，用于任务调度、带权图的最短路径算法（如Dijkstra）。

    4.数据压缩​：使用哈夫曼树（最优二叉树）：
        根据字符出现频率构建带权路径最短的树，生成哈夫曼编码，用于ZIP、JPEG等压缩。

    5.表达式求值​：使用表达式树：
        树叶是操作数，内部节点是运算符，通过遍历树可以方便地计算表达式值或生成前缀、后缀表达式。

    6.编译器​：使用语法树：​
        将源代码的语法结构表示为树，是语法分析、代码优化和生成的中间表示。

    7.文件系统与数据库索引​：使用B树/B+树（多路平衡树）：
        可以看作是二叉搜索树向“多叉”的扩展，减少磁盘I/O次数，是数据库和文件系统的核心索引结构。

    8.决策系统​：使用决策树：​
        机器学习中的分类模型，每个节点代表一个判断条件，分支代表结果，叶子代表最终类别。
*/



/*
证明题：对满二叉树编号，根节点从1开始，从上到下从左到右，对于编号为i的节点，若存在左孩子，则
    左孩子的编号为2i，右孩子为2i+1。

证明：通过数学归纳法，对于i=1，左孩子编号为2，右孩子编号为3，成立。
    对于第i个节点(i>1)，设其处于第L层，由满二叉树可得：
        (1)第L层有2^(L−1)个节点，而前L层(包括L)总共2^L−1个节点，故第L层编号从2^(L−1)到2^L−1。
        (2)节点i处于L层中的位置(从左到右)为：p=i−2^(L−1)+1（即第p个节点）。
    节点i之前的节点（在第 L层）共有：p−1=i−2^(L−1)个。每个节点都有两个子节点，因此在第L+1层
        中，位于节点i的子节点之前的节点数为：2×(i−2^(L−1))。
    第L+1层的节点编号从2^L开始。因此，节点i的左孩子的编号为：
                2^L+2(i−2^(L−1)) = 2^L+2i+2^L = 2i
    那么右孩子的编号便是2i+1。证毕。
*/