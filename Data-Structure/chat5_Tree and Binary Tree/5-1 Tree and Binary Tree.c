/*
树(Tree)：
一、定义：
    1.树是 n（n ≥ 0）个节点​的有限集合（当 n=0 时，称为空树）。在非空树中：
        有且仅有一个特定的节点称为根节点；
        其余节点可分为 m（m ≥ 0）个互不相交的有限集合，每个集合本身又是一棵树，称为根的子树。

    2.树是递归定义的，这为其算法设计（如遍历、搜索）提供了天然基础。


二、基本概念：
    概念名词：
        1.节点​：树中的每个元素，包含数据项及指向子树的指针。
        2.根节点​：树的最顶层节点，没有父节点。
        3.父节点/双亲：若一个节点有子节点，则该节点是其子节点的父节点或双亲。
        4.子节点/孩子：​一个节点的直接后继节点。
        5.兄弟节点：​具有相同父节点的节点。
        6.叶子节点(终端节点)​：没有子节点的节点。
        7.子树​：节点及其后代构成的树。
        8.森林​：m（m ≥ 0）棵互不相交的树的集合。

    用于计算的量名词：
        9.节点的度​：节点拥有的子树个数（子节点个数，若没有则为0）。
        10.树的度​：树中各节点度的最大值。
        11.层次​：节点的层次从根开始，根为第1层(或第0层)，根的孩子(子节点)为第二层，往下递增。
        12.深度/高度：​树中节点的最大层次数。
        13.路径​：从节点 n1 到 nk 的节点序列，相邻节点存在父子关系。
        

三、树的特点：
    1.分层结构：数据按层次组织，上层节点与下层节点存在一对多关系。
    2.唯一的根：每个非空树有且仅有一个根节点。
    3.子树互不相交：任意两个子树之间没有公共节点。
    4.递归定义：树由根节点和若干子树构成，子树也是树。
    5.非线性：节点之间存在分支关系，不同于线性结构的顺序排列。


四、重要性质：
    1.最重要的性质————总节点数计算：树中所有节点数 = 所有节点的度数之和 + 1
        解释：从最高层的枝叶开始，依次计算每层所有节点的度数之和，该值就是高一层的节点数，那么计算
            到最底层根节点时，根节点的度数就是倒数第二层节点数，那么所有节点的度数之和就是除根节点
            外的所有节点数，最后+1便补上了根节点的数目。

    2.第i层最大节点数(令根节点为第1层)：若树的度为d，则第i层最多有d^(i−1)个节点(i ≥ 1)
        解释：最多的节点数便对应每层节点数满的，即其父节点都是树的度数d，那么第一层根节点为1个，
            第二层为d个节点，以此类推，构成比为d的等比数列，那么第i层便是d^(i−1)个。

    3.高度为h的树最多节点数：度为d的树最多有(d^h−1)/(d−1)个节点（满树情况）。
        解释：同样按照2的等比数列情形，则高为h的树的节点数为前h项比为d的等比数列的求和。

    4.树的边数计算：若树有n个节点，则树中有n-1条边。
        解释：因为除根外的节点都有一条边指向父节点，形成一一对应关系。


五、树的作用与应用场景：
    1.文件系统​：目录与文件的层次结构（如 Unix/Linux 目录树）。
    2.数据库索引​：B树、B+树用于高效检索（减少磁盘 I/O）。
    3.组织架构​：公司部门层级关系。
    4.决策树​：机器学习中的分类与回归模型。
    5.语法分析​：编程语言编译器的语法树（AST）。
    6.游戏AI​：博弈树搜索（如棋类游戏）。
    7.网络路由​：组播树、最小生成树（MST）用于网络优化。
    8.XML/HTML解析​：DOM 树表示文档结构。


六、常见的树类型：
    1.二叉树：每个节点最多有两个子节点（左、右子树），是许多高级树结构的基础。
    2.完全二叉树：除最后一层外，其他每一层节点数都达到最大值，并且最后一层节点都从最左边连续排列。
    3.二叉搜索树（BST）：左子树所有节点值 < 根节点值 < 右子树所有节点值，支持高效查找。
    4.平衡二叉树（如 AVL 树、红黑树）：通过旋转保持平衡，保证操作时间复杂度为 O(log n)。
    5.堆：完全二叉树，用于实现优先队列。
    6.字典树（Trie）：用于字符串检索、自动补全。
    7.B树/B+树：多路平衡树，用于数据库和文件系统索引。


七、树的数据结构：
    1.顺序存储结构：一般只用于存储"满二叉树或完全二叉树"情形，因为其他树会导致很多数组空间是空的。
    2.链式存储结构：树的常用存储格式。

    
八、总结：
    树之所以成为数据结构中的核心内容，是因为它：
        1.自然地表示层次关系（如家谱、目录）；
        2.支持高效的查找、插入、删除操作（尤其平衡树）；
        3.是许多高级算法和系统（数据库、编译器、AI）的基础组件。
*/



