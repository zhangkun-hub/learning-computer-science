#include<stdio.h>
#include <stdlib.h>

typedef int ElemType;

// 创建单链表的节点格式
typedef struct node{
    ElemType data;      // 创建存储节点的数据元素
    struct node* next;  // 创建存储下一个节点的内存地址(注意:下一个节点的类型仍然是struct node)
}Node;

// 单链表初始化————头节点的创建
Node* initList()
{
    Node* head = (Node*)malloc(sizeof(Node));
    head->data = 0;
    head->next = NULL;  // 因为之后没有节点，所以指向空内存地址
    return head;
}

int main()
{
    Node* list = initList();

    free(list);

    return 0;
}

