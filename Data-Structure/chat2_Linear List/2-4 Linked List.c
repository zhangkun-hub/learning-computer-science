/*
链表：
一、线性表链式存储结构的特点：用一组任意的存储单元存储线性表的数据元素。
                    注意：这组存储单元的内存地址可以是连续的，也可以是不连续的。

二、特点：为了表示每个数据元素ai与其直接后继数据元素ai+1之间的逻辑关系，对数据元素ai来说，除了
        其本身的信息之外，还需要存储一个指示其直接后继的信息(即直接后继的存储位置)。这两部分
        信息组成数据元素ai的存储映像，称为节点(node)。

三、节点特性：
    1.节点包括两个域：其中存储数据元素信息的称为数据域；存储直接后继存储位置的域称为指针域。
                        指针域中存储的信息称作指针或链。
            
    2.n个节点[ai(1 ≤ i ≤ n)的存储映像]链接成一个链表，即为链表(a1, a2,…, an)。

四、链表的建立：
    1.不能由一个结构体完整的表示，而是用一个结构体表达一个节点。

    2.只需关注头节点(即第一个节点)，就能通过链式结构找到后面所有的内容。
            注意：头节点的数据域一般不存储任何数据信息，只在数据域做一个特殊值处理(比如-1)用来
        表示他是头节点，然后在头节点后的一个节点真的保存数据信息(当然有些链表可以不这样操作)。

    3.如果头节点的数据域不存储数据，那么链表真正存储数据的索引从1开始而不是从0开始，
        而链表的长度包不包括头节点随意，根据实际情况确定。

    4.对于最后一个节点的指针域，因为之后没有节点，所以其指针直接赋值为NULL(空内存地址)。


五、链表的优缺点：
    1.优点：
        (1)真正的动态大小，无需预分配：
            每个节点独立分配，可以随时轻松地添加新节点，几乎没有容量限制（受总内存限制）。

        (2)插入和删除效率高(已知节点位置时为O(1)复杂度，这是其最大的优势)： 
            在已知节点指针/引用的情况下，插入或删除节点只需要修改几个指针，无需移动任何数据。

    2.缺点：
        (1)不支持随机访问，查找效率低(O(n))： 
            要访问第i个元素，必须从头节点开始逐个遍历。这使得二分查找等高效算法无法直接应用。

        (2)内存开销大：
            每个节点不仅要存储数据元素，还需要额外的空间来存储指向下一个(或前一个)节点的指针。

        (3)内存局部性差，缓存不友好：节点在内存中分散存储，访问时对CPU缓存不友好，
            可能导致更多的缓存未命中，实际访问速度可能比理论慢。


六、链表的种类：
    1.单链表：单一方向，即每个节点后只存储下一个节点的位置信息(单链表建立与各种操作见2-5的代码)
        (1)优点：
            (a)内存开销最小：每个节点只需存储1个指针
            (b)结构简单：实现和维护容易
            (c)插入/删除头部高效：O(1)时间复杂度

        (2)缺点：
            (a)只能单向遍历：无法反向访问
            (b)删除节点需要前驱：删除指定节点需要O(n)时间找到其前驱
            (c)反向遍历困难：需要额外空间或递归

        (3)适用场景：
            (a)栈的实现（只需要操作头部）
            (b)简单的FIFO队列
            (c)内存极度受限的环境
            (d)只需要单向处理的数据（如多项式相加）

    2.双链表：两个方向，即每个节点后存储下一个节点与上一个节点的位置信息。
        (1)优点：
            (a)双向遍历：可向前或向后遍历
            (b)删除节点方便：已知节点指针时，删除只需O(1)时间
            (c)插入灵活：可在节点前后插入
            (d)反向操作高效：支持反向查找和操作

        (2)缺点：
            (a)内存开销大：每个节点多一个指针，额外开销33%-50%
            (b)操作复杂：插入删除需要维护两个指针
            (c)实现更复杂：容易出错，特别是边界情况

        (3)适用场景：
            (a)LRU缓存淘汰算法：需要快速移动节点到头部
            (b)浏览器的前进/后退：需要双向导航
            (c)文本编辑器的撤销/重做
            (d)双端队列(Deque)​ 的实现

    3.循环链表：将链表的头和尾链接起来(当然，循环链表也有单链表双链表之分，含义完全类似)。
        (1)优点：
            (a)可从任意节点遍历整个链表
            (b)无真正的头尾概念：某些算法更简洁
            (c)空间利用灵活：不需要特殊处理头尾指针
            (d)循环双链表删除尾节点高效：O(1)时间

        (2)缺点：
            (a)遍历需注意终止条件：容易死循环
            (b)空链表处理特殊：需要特殊标记
            (c)实现稍复杂：循环连接需要仔细维护

        (3)特有优势场景：
            (a)约瑟夫问题：循环淘汰
            (b)轮询调度：Round-Robin调度
            (c)循环队列：固定大小的缓冲区
            (d)多人游戏轮流操作
*/
