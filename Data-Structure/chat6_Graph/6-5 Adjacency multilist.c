/*
邻接多重表（针对无向图）
一、结构：专门为无向图设计，解决邻接表中同一条边被存储两次（分别在两个端点的链表中）带来的
        数据不一致和操作冗余问题。
    每条边用一个节点表示，该节点同时被链接到它所关联的两个顶点的边链表中。

二、特点与性质：
    1.每条边只存储一次。
    2.空间复杂度和邻接表相同，为O(n + e)。

三、优点：
    1.边操作更高效：删除一条边、标记一条边等操作，只需在一个边节点上进行，避免了在邻接表中
        需要修改两个链表的麻烦。
    2.数据一致性更好。

四、缺点：
    结构比邻接表稍复杂。

五、应用场景：   
    需要对边进行频繁操作（如删除、标记）的无向图，例如在求解最小生成树的算法中。
*/