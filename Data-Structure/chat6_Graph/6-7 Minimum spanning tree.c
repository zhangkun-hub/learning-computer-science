/*
一、最小生成树：
    1.生成树：对于一个带权连通无向图，其生成树是它的一个子图，且该子图必须同时满足以下两个条件：
            (1)是一棵树：这意味着它无任何回路，并且无孤立顶点。
            (2)是生成树：它包含原图的所有顶点。

    2.最小生成树：权重最小：在所有满足前两个条件的生成树中，它的所有边的权重总和最小。
        理解：现实很多问题都可以抽象为：用最低的总成本，将一系列地点(顶点)连通，且保证彼此可达。

    3.关键特性与解释
        (1)前提是连通图：只有连通图才存在生成树。对于非连通图，得到的是“最小生成森林”。
        (2)边数固定：一个具有 V个顶点的最小生成树，恰好有 V - 1​ 条边。
        (3)不唯一性：如果图中存在多条权重相同的边，那么最小生成树可能不唯一。但所有最小生成树的
            总权重是相同的，且都是最小的。
        (4)与最短路径的区别：最小生成树追求的是全局连接所有顶点的总成本最低，而最短路径（如
            Dijkstra算法）解决的是两点之间的成本最低问题。两者目标不同。


二、Prim算法：
    1.算法概述：Prim算法是一种用于求解加权无向连通图的最小生成树的贪心算法。它从一个顶点开始，
        逐步扩展生成树，每次选择连接生成树与剩余顶点之间的最小权重边，直到包含所有顶点。

    2.核心原理：基于顶点，从一点逐步扩展：
        (1)从任意顶点开始，逐步构建最小生成树
        (2)每次选择连接已选顶点集合与未选顶点集合之间的权重最小的边
        (3)将该边及其连接的未选顶点加入生成树
        (4)重复直到所有顶点都加入生成树

    3.算法步骤：输入：加权无向连通图G = (V, E)，其中V是顶点集合，E是边集合
               输出：最小生成树T
        (1)初始化：选择任意起始顶点s，将s加入集合S（已选顶点集），其余顶点加入集合 V-S
        (2)初始化优先队列/最小堆：将与 s 相连的所有边加入优先队列
        (3)循环直到 S 包含所有顶点：
            (a)从优先队列中取出权重最小的边 (u, v)，其中 u ∈ S，v ∈ V-S
            (b)将边 (u, v) 加入最小生成树 T
            (c)将顶点 v 加入集合 S
            (d)将顶点 v 连接的所有边（指向 V-S 中顶点的边）加入优先队列
        (4)返回最小生成树 T

    4.优点：
        (1)简单直观：算法思想易于理解，实现相对简单
        (2)确定性：对于给定的图，Prim算法总能找到唯一的最小生成树（当所有边权重不同时）
        (3)适用于稠密图：在邻接矩阵表示下，时间复杂度为 O(V²)，对稠密图效率高
        (4)贪心选择性质：每一步的局部最优选择能保证全局最优解
        (5)适合边数多的图：当边数接近完全图时，Prim算法通常比Kruskal算法更高效

    5.缺点：
        (1)需要连通图：只能处理连通图，对于不连通图需要分别处理每个连通分量
        (2)边权重需非负：算法基于贪心选择，负权重边可能破坏贪心选择性质
        (3)内存消耗：需要存储整个图的邻接矩阵或优先队列
        (4)不适合动态图：当图结构频繁变化时，需要重新计算

    6.时间复杂度分析
        数据结构	           时间复杂度	    适用场景
        邻接矩阵 + 简单查找	    O(V²)	        稠密图，实现简单
        邻接表 + 二叉堆	        O(E log V)	    稀疏图，常用实现
        邻接表 + 斐波那契堆	    O(E + V log V)	理论最优，实现复杂

    7.实际应用：最常用的是邻接表 + 优先队列（二叉堆）实现，时间复杂度 O(E log V)。


三、Kruskal算法：
    1.算法概述：Kruskal算法是一种用于求解加权无向图的最小生成树的贪心算法。与Prim算法从顶点扩展
        不同，Kruskal算法从边的角度出发，每次选择权重最小的边，并确保不形成环，直到包含所有顶点。

    2.核心原理：基于边，按权重排序选择：
        (1)将图中所有边按权重从小到大排序
        (2)初始化一个空的边集合（最小生成树的边）
        (3)按顺序考虑每条边：
        (4)如果将这条边加入集合不会形成环，就加入
        (5)否则，跳过这条边
        (6)重复直到选择了V-1条边（V为顶点数）

    3.算法步骤：输入：加权无向图 G = (V, E)，其中 V 是顶点集合，E 是边集合
               输出：最小生成树 T 的边集合
        (1)对 E 中所有边按权重进行升序排序。
        (2)初始化：T = ∅，创建并查集，每个顶点自成一个集合(一般用数组parent[]表示)。
                (注：并查集与最小生成树不是同一个东西，其具体内容请见最下面补充内容)
        (3)对于排序后的每条边(u, v, weight)：
            (a)进行find(u)和find(v)操作（find(u)是并查集的查找操作，查找u的根节点）。
            (b)如果find(u) ≠ find(v)（即u和v不在同一个连通分量中(也就是不在同一棵树上)），
                将边(u, v, weight)加入T，并执行union(u, v)操作（并查集的合并操作，将u的根节点
                父节点设为v的根节点，从而将两棵树合并成一棵树，此时u和v在同一个连通分量中）
            (c)如果 |T| = V-1，算法结束。
        (4)返回 T。
        
    4.优点
        (1)简单直观：算法思想非常直接，容易理解和实现
        (2)适用于稀疏图：时间复杂度主要取决于边的排序，当边数较少时效率高
        (3)可处理不连通图：可以生成最小生成森林（多个连通分量的最小生成树）
        (4)边处理独立：每条边的处理是独立的，适合并行化
        (5)不需要指定起点：从全局最优的角度选择边

    5.缺点
        (1)需要排序：时间复杂度受排序算法影响，为O(E log E)
        (2)并查集开销：需要额外的并查集数据结构来判断是否形成环
        (3)在稠密图中效率较低：当边数很多时，排序开销较大
        (4)内存消耗：需要存储所有边并进行排序

    6.时间复杂度分析
        步骤	     时间复杂度	                说明
        边排序	     O(E log E)	               使用快速排序、归并排序等
        并查集操作	 O(α(V)) ≈ O(1)	            每次查找/合并接近常数时间
        总复杂度	 O(E log E)​ 或 O(E log V)​	  最坏情况下 E = O(V²)

        注意：由于 log E ≤ 2 log V，所以 O(E log E) = O(E log V)


四、Kruskal算法与Prim算法的详细对比与选择指南：
    1.详细对比：
        特性	       Kruskal算法	                  Prim算法
        基本思想​	    基于边，按权重排序选择	         基于顶点，从一点逐步扩展
        数据结构​	    并查集 + 排序的边	             优先队列/邻接矩阵
        时间复杂度​	    O(E log E) 或 O(E log V)	    二叉堆: O(E log V)，邻接矩阵: O(V²)
        空间复杂度​	    O(E)                            存储边	O(V²) 或 O(V+E)
        适用图类型​	    稀疏图（边数E远小于V²）	          稠密图（边数E接近V²）
        图连通性​	    可处理不连通图（得最小生成森林）   必须连通图
        是否需要起点​	不需要	                         需要指定起点
        实现复杂度​	    中等（需实现并查集）	          相对简单
        内存使用​	    需存储所有边	                 需存储图结构
        并行潜力​	    较高（边处理独立）	              较低（顶点扩展有依赖）
        实际性能​	    稀疏图中通常更快	              稠密图中通常更快

    2.选择指南：
        选择Kruskal的情况：
            (1)图是稀疏的：E << V²，排序开销相对较小
            (2)边已经预先排序：如果边已按权重排序，Kruskal接近线性时间
            (3)需要处理不连通图：需要得到最小生成森林
            (4)内存有限：可以流式处理边，不需要同时存储整个图
            (5)并行计算：可以并行排序边和处理边、

        选择Prim的情况：
            (1)图是稠密的：E ≈ V²，此时Prim的O(V²)优于Kruskal的O(E log E)
            (2)需要从特定点开始：如网络布线必须从中心节点开始
            (3)图动态变化：添加顶点时Prim更容易更新
            (4)使用邻接矩阵存储：Prim可以直接利用矩阵结构
            (5)需要多次查询MST：可以缓存中间结果
*/

/*
补充内容————并查集(Union-Find)
    1.基本定义：
        并查集是一种树型的数据结构，用于处理不相交集合的合并与查询问题。它支持以下两种操作：
            Find：确定元素属于哪个子集
            Union：将两个子集合并为一个集合


    2.最基本作用：在动态变化的连通关系中，通过并查集可以判断每次动态变化中两个节点是否连通，当两个
        节点不属于同一个集合，那就是不连通的(否则就是)，然后将两子集合并，就表示这原本不相交的子集
        的元素节点就都相连通了，这就是动态变化的连通关系，然后进行下一次并查集操作，持续下去。
            这个作用可以衍生出一系列的应用场景(见第6部分)


    3.核心思想：用一棵树来代表一个集合，树的根节点作为这个集合的“代表元”。
        (1)查找：确定某个元素属于哪个集合，就是通过不断查找父节点，直到找到根节点（代表元）。
        (2)合并：将两个不相交集合合并，就是将其中一棵树的根节点，连接到另一棵树的根节点上。


    4.算法步骤与代码实现(设节点数为n，节点数据是int类型)：
        (1)通常使用一个数组parent[]来记录每个节点的父节点，具体含义如下：
            数组索引：表示节点的编号。
            数组值：正数：表示该节点的父节点索引。
                    负数（通常-1）：表示该节点是根节点，且集合大小为1。

        (2)初始化：每个节点各自构成一个单独的集合，即自己是自己的根。
            for (int i = 0; i < n; i++)
            {
                parent[i] = -1;
            }

        (3)查找：找到节点x所在集合的根节点（代表元）。
            int find(int* parent, int x)
            {
                while (parent[x] > -1)  // 当前节点不是根节点
                {
                    x = parent[x];  // 向上找父节点
                }
                return x;  // 返回根节点
            }

        (4)合并：将节点a和节点b所在的集合合并。
            void unionSets(int* parent, int a, int b) 
            {
                int rootA = find(parent, a);  // 找到a的根
                int rootB = find(parent, b);  // 找到b的根
                
                if (rootA != rootB)  // 如果两个根不相等(即不在同一个树集合中)
                {  
                    parent[rootA] = rootB; // 合并：将rootA的父节点设为rootB
                }
            }


    5.特点：
        高效：在上述代码再次经过优化后，操作效率可接近常数时间。
        简洁：代码实现非常简短，核心只有 find和 union两个函数。
        动态：非常适合处理动态变化的连通关系，集合可以随时合并。


    6.应用场景：
        维护无向图的连通分量：判断两个节点是否连通，或计算连通块数量，是并查集的经典应用。
        Kruskal算法求最小生成树：用于高效判断加入一条边后是否会形成环。
        社交网络中的朋友关系：快速判断两个人是否属于同一个朋友圈（间接朋友）。
        编译器中的等价变量判断。
        游戏中的棋盘连通性检查（如围棋、黑白棋）。
        解决一些看似复杂的数学等式/不等式关系问题（如判断变量是否相等）。
*/
