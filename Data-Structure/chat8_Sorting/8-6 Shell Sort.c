/*
希尔排序(Shell Sort)：希尔排序是插入排序的改进版本，也称为缩小增量排序。
一、算法思想：
    分组：将待排序数组按增量（步长）分成若干子序列。
    子序列排序：对每个子序列进行插入排序(插入排序见8-4)。
    缩小增量：逐步减小增量，重复步骤分组和子序列排序。
    最终排序：当增量为1时，对整个数组进行插入排序。
    
    注：1.Shell原始序列：长度为n的数组的子序列的增量(步长)依次为：n/2, n/4,..., 1。
        2.算法作用：克服了插入排序只能相邻交换的低效问题，允许跨越多个位置的交换，从而提高了效率。


二、算法步骤：
    1.基本步骤(使用Shell原始序列)：
        第1步：确定初始增量：
            (1)获取数组长度 n
            (2)初始增量 step = n // 2
        第2步：外循环 - 控制增量递减：
            当 step >= 1 时，重复以下3-4步
        第3步：内循环 - 对每个子序列进行插入排序：
            对于 i 从 step 到 n-1，执行：
                (1)保存当前元素：temp = arr[i]
                (2)初始化比较位置：j = i - step
                (3)当 j ≥ 0 且 arr[j] > temp 时，执行：
                    a. 将前一个元素后移：arr[j + step] = arr[j]
                    b. 向前移动比较位置：j = j - step
                (4)将temp插入正确位置：arr[j + step] = temp
        第4步：减小增量：step = step // 2
        第5步：结束外循环：当 step = 0，此时数组已完全有序

    2.增量序列的选择：增量序列的选择是希尔排序性能的关键
        增量序列	    公式	                        最坏时间复杂度	  提出者
        Shell原始序列	n/2, n/4, ..., 1	            O(n²)	        Donald Shell
        Hibbard序列	    1, 3, 7, 15, ..., 2^k-1	        O(n^{3/2})	    Hibbard
        Knuth序列	    1, 4, 13, 40, ..., (3^k-1)/2	O(n^{3/2})	    Donald Knuth
        Sedgewick序列	1, 5, 19, 41, 109, ...	        O(n^{4/3})	    Robert Sedgewick


三、希尔排序的特点
    1.优点
        改进的插入排序：克服了插入排序只能相邻交换的缺点
        原地排序：空间复杂度O(1)，不需要额外存储空间
        中等规模高效：在几千到几万的数据规模上表现良好
        算法简单：比快速排序、归并排序等实现简单
        自适应：对部分有序数据效率更高
        不稳定但实用：虽然不稳定，但在实际应用中很有价值

    2.缺点
        不稳定排序：相等元素的相对顺序可能改变
        时间复杂度分析困难：与增量序列密切相关
        性能不稳定：不同增量序列性能差异大
        不如高级算法：在大数据量上不如快速排序、归并排序
        增量序列选择困难：没有统一的"最佳"增量序列

    
四、时间复杂度分析
    1.希尔排序的时间复杂度高度依赖增量序列的选择：
        增量序列	    最坏时间复杂度	 平均时间复杂度	   说明
        希尔原始序列	 O(n²)	         O(n^{1.5})	     简单但不稳定
        Hibbard序列	    O(n^{3/2})	    O(n^{5/4})	    明显改进
        Sedgewick序列	O(n^{4/3})	    O(n^{7/6})	    当前最优之一
        Knuth序列	    O(n^{3/2})	    O(n^{5/4})	    稳定改进
        注意：
            (1)希尔排序的精确时间复杂度分析是未解决的数学问题，上表是基于实验和经验的结果。
            (2)实际应用中，希尔排序通常比O(n²)算法快得多，比如对于中等规模数据(n=1000-10000)，
                    性能接近O(n log n)算法

    2.空间复杂度：O(1)（原地排序）


五、价值与应用：
    1.希尔排序的核心价值：
        历史意义：第一个突破O(n²)的排序算法
        简单高效：实现相对简单，性能优于O(n²)算法
        原地排序：空间复杂度O(1)，适合内存受限环境
        自适应：对部分有序数据效率高

    2.实际应用建议：
        在内存严格受限的环境中考虑使用
        在中等规模数据（n<50000）上是不错的选择
        作为混合排序算法的组成部分
        在嵌入式系统或特殊硬件上可能有优势
*/
#include <stdio.h>

// 希尔排序(采用Shell原始序列)
void shellSort(int* data, int len)
{
    int temp;
    int step = len / 2;  // 初始化步长为数组长度的一半

    // 当步长不小于1时便一直进行子序列插入排序
    while(step >= 1)
    {
        // 对每个子序列执行插入排序
        for (int i = step; i < len; i++)
        {
            // 当前元素小于其步长距离前的元素 -> 执行插入排序
            if (data[i] < data[i - step])
            {
                temp = data[i];  // 暂存当前值
                int j = i - step;

                // 向前寻找合适插入位置，并逐步移动大于 temp 的元素
                while(j >= 0 && temp < data[j])
                {
                    data[j + step] = data[j];  // 将较大值后移
                    j = j - step;
                }
                // 插入 temp 到正确位置
                data[j + step] = temp;
            }
        }
        // 按Shell原始序列进行步长缩小，即除以2
        step = step / 2;
    }
}

int main(int argc, char const *argv[])
{
    // 待排序数组
    int data[] = {47, 35, 60, 95, 77, 15, 28, 52};
    int len = sizeof(data) / sizeof(data[0]);  // 计算数组长度

    // 调用希尔排序
    shellSort(data, len);  
    
    // 输出排序结果
    for(int i = 0; i < len; i++)
    {
        printf("%d ", data[i]); // 15 28 35 47 52 60 77 95
    }
    return 0;
}