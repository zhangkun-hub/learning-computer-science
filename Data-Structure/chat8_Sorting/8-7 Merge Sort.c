/*
归并排序(Merge sort)：是一种基于分治法（Divide and Conquer）的稳定排序算法
一、核心思想：
    1. 分：将数组从中间分成两个子数组
    2. 治：递归地对两个子数组进行归并排序(即重复分、治操作)
    3. 合：将两个有序的子数组合并为一个有序数组

二、算法步骤：
    1.具体步骤：
        步骤1：递归分解
            - 如果数组长度小于等于1，直接返回（已有序）
            - 否则，找到中间位置 mid = (left + right) // 2
            - 递归排序左半部分 [left, mid]
            - 递归排序右半部分 [mid+1, right]

        步骤2：合并两个有序子数组
            - 创建临时数组存储合并结果
            - 使用两个指针分别指向两个子数组的起始位置
            - 比较两个指针指向的元素，将较小的放入临时数组
            - 移动指针，重复直到一个子数组被完全处理
            - 将另一个子数组的剩余元素复制到临时数组
            - 将临时数组复制回原数组对应位置

    2.合并过程具体实例：
        左子数组：[3, 27, 38, 43]    右子数组：[9, 10, 82]
        指针i=0                     指针j=0
        临时数组：[]

        比较 arr1[0]=3 和 arr2[0]=9 → 3较小 → temp=[3], i=1
        比较 arr1[1]=27 和 arr2[0]=9 → 9较小 → temp=[3,9], j=1
        比较 arr1[1]=27 和 arr2[1]=10 → 10较小 → temp=[3,9,10], j=2
        比较 arr1[1]=27 和 arr2[2]=82 → 27较小 → temp=[3,9,10,27], i=2
        比较 arr1[2]=38 和 arr2[2]=82 → 38较小 → temp=[3,9,10,27,38], i=3
        比较 arr1[3]=43 和 arr2[2]=82 → 43较小 → temp=[3,9,10,27,38,43], i=4
        左子数组已空，复制右子数组剩余元素 → temp=[3,9,10,27,38,43,82]


三、归并排序的特点
    1.优点
        稳定性：相等元素的相对顺序保持不变
        时间复杂度有保证：最坏、最好、平均情况都是O(n log n)
        适合大数据：可处理大规模数据集
        适合外部排序：可用于磁盘文件等外部存储的排序
        适合链表：可高效排序链表（空间复杂度O(1)）

    2.缺点
        需要额外空间：需要O(n)的额外存储空间
        递归开销：递归实现有函数调用开销
        常数因子较大：实际运行常数比快速排序大
        不适合小数组：对小数组，插入排序等更高效


四、时间复杂度分析
    情况	     时间复杂度	    说明
    最优情况	 O(n log n)	    无论输入如何，都要分解和合并
    最坏情况	 O(n log n)	    同样需要完整的分解和合并
    平均情况	 O(n log n)	    随机数据的期望性能
    空间复杂度	 O(n)	        需要临时数组存储合并结果

    注：详细分析：
        分解：每次将数组二分，递归深度为log₂n
        合并：每层需要合并n个元素
        总时间：O(n) × O(log n) = O(n log n)


六、总结
        归并排序是一种稳定、高效、通用的排序算法，其分治思想是算法设计的经典范例。虽然需要额外
    O(n)空间，但其稳定的O(n log n)性能使其在需要稳定排序、处理大数据、外部排序等场景中无可替代。

    1.核心价值：
        稳定性：保持相等元素的相对顺序
        性能保证：最坏情况O(n log n)
        适用性广：适合数组、链表、外部存储
        可并行化：易于并行实现

    2.实际应用：
        数据库查询结果的排序
        大数据处理（MapReduce）
        文件系统排序
        编程语言内置排序（如Python的Timsort）

    3.现代发展：
        Timsort：Python、Java、Android等使用的混合排序算法
        并行归并排序：多核CPU上的高效实现
        外部排序：处理超过内存的数据
*/
#include <stdio.h>

// 合并两个有序子序列
// 第一个子序列是 data[left...mid]
// 第二个子序列是 data[mid+1...right]
void merge(int* data, int left, int mid, int right)
{
    int temp[100]; // 临时数组，用于存放合并结果
    int i = left;  // 左半部分起始索引
    int j = mid + 1; // 右半部分起始索引
    int k = 0;     // temp 数组下标

    // 将两个有序部分按照大小关系依次放入 temp 中
    while (i <= mid && j <= right)
    {
        if (data[i] <= data[j])
        {
            temp[k++] = data[i++];
        }
        else
        {
            temp[k++] = data[j++];
        }
    }

    // 将剩余的左边部分拷贝到 temp 中（如果有）
    while (i <= mid)
    {
        temp[k++] = data[i++];
    }

    // 将剩余的右边部分拷贝到 temp 中（如果有）
    while (j <= right)
    {
        temp[k++] = data[j++];
    }

    // 将 temp 中的结果拷贝回原数组中，完成合并
    for (int t = 0; t < k; t++)
    {
        data[left + t] = temp[t];
    }
}

// 归并排序的递归函数
// 对 data[left...right] 这一段进行排序
void mergeSort(int* data, int left, int right)
{
    if (left < right) // 至少两个元素才需要排序
    {
        int mid = (left + right) / 2;

        // 对左半部分排序
        mergeSort(data, left, mid);

        // 对右半部分排序
        mergeSort(data, mid + 1, right);

        // 将排好序的左右两部分合并
        merge(data, left, mid, right);
    }
}

int main(int argc, char const *argv[])
{
    // 待排序数组
    int data[] = {47, 35, 60, 95, 77, 15, 28, 52, 80};
    int len = sizeof(data) / sizeof(data[0]);

    // 对数组进行归并排序
    mergeSort(data, 0, len - 1); 

    // 输出排序后的结果
    for (int i = 0; i < len; i++)
    {
        printf("%d ", data[i]); // 15 28 35 47 52 60 77 80 95
    }
    return 0;
}