/*
堆与堆排序：
一、堆：(特别注意：这里的堆跟堆内存的堆没有关系)
    1.定义：堆是一种特殊的完全二叉树数据结构，它满足以下性质之一：
            (1)最大堆（大根堆/大顶堆）
                每个节点的值都大于或等于其子节点的值
                根节点是最大值
            (2)最小堆（小根堆/小顶堆）
                每个节点的值都小于或等于其子节点的值
                根节点是最小值

    2.堆的性质
        (1)完全二叉树：除了最后一层，其他层都是满的，最后一层从左到右填充
        (2)堆序性：父节点和子节点之间的大小关系满足堆定义
        (3)数组表示：堆通常用数组存储，具有以下映射关系(具体见5-1完全二叉树的性质)：
            节点i的父节点：parent(i) = floor(i/2) (i>1)，其中floor函数表示向下取整。
            节点i的左子节点：left(i) = 2*i (若 2*i ≤ n)。
            节点i的右子节点：right(i) = 2*i + 1 (若 2*i + 1 ≤ n)。

    3.堆的插入与删除操作：
        (1)插入操作：
            a.保证形态为完全二叉树的基础上插入(也就是插入到最后一个节点的下一位处)。
            b.插入后再按照最大堆/最小堆要求，从插入点的父节点开始，逐层向上调整。

        (2)删除操作：
            a.用最后一个节点替换要删除的节点，然后删掉最后一个节点。
            b.按照最大堆/最小堆要求，从根节点开始，逐层向下调整。


二、堆排序：
    1. 堆排序的基本思想：
        堆排序是利用堆的性质进行排序的算法，分为两个主要步骤：
            建堆：将无序数组构建成一个堆
            排序：重复从堆中取出最大/最小元素

    2. 算法步骤（升序使用最大堆）：
        (1)第一阶段：构建最大堆；目标：将无序数组调整为一个最大堆
            步骤1.1：从最后一个非叶子节点开始
                - 计算最后一个非叶子节点的索引：floor(n/2)（即向下取整）
                - 从该节点开始，向前遍历到根节点（索引0）
            步骤1.2：对每个节点进行堆调整（heapify函数）
                for i = n/2-1 downto 0:
                    调用 heapify(arr, n, i)
                    # 即从下往上、从右往左调整，确保每个子树都满足堆性质

        (2)第二阶段：排序过程；目标：重复从堆中提取最大元素并调整堆
            注：该阶段操作本质就是不断进行堆的删除操作，而删除的元素就作为未排序数组的最后一个元素
            步骤2.1：交换堆顶与末尾元素
                for i = n-1 downto 1:
                    # 将当前最大元素（堆顶）移动到数组末尾
                    交换 arr[0] 和 arr[i]
            步骤2.2：调整剩余堆
                # 堆大小减1（排除已排序的末尾元素）
                调用 heapify(arr, i, 0)
                # 只需要调整根节点，因为其他部分已满足堆性质

        (3)核心辅助函数————堆调整（heapify）；目标：确保以给定节点为根的子树满足堆性质
            函数 heapify(arr, root_index, heap_size):
            步骤3.1：初始化
                largest = root_index         # 假设根节点是最大值
                left = 2 * root_index        # 左子节点索引
                right = 2 * root_index + 1   # 右子节点索引
            步骤3.2：在根节点和子节点中找出最大值
                if left <= heap_size 且 arr[left] > arr[largest]:
                    largest = left
                if right <= heap_size 且 arr[right] > arr[largest]:
                    largest = right
            步骤3.3：如果最大值不是根节点，则交换并递归调整
                if largest != root_index:
                    交换 arr[root_index] 和 arr[largest]
                    # 递归调整被影响的子树
                    调用 heapify(arr, largest, heap_size)

    3.堆排序的特点
        (1)优点
            时间复杂度优秀：最好、最坏、平均情况都是O(n log n)
            原地排序：空间复杂度O(1)，不需要额外存储空间
            最坏情况有保障：不像快速排序可能退化到O(n²)
            适合大数据：在数据量很大时表现稳定
            可以部分排序：只需构建堆就能快速获取前k个最大/最小值

        (2)缺点
            不稳定排序：相同值的元素可能改变相对顺序
            缓存不友好：对数组的非顺序访问导致缓存命中率低
            实现较复杂：比快速排序、归并排序更复杂
            递归开销：堆调整使用递归，可能栈溢出（可改为迭代）

    4.时间复杂度分析
        步骤	        时间复杂度	     说明
        建堆	        O(n)	        看似O(n log n)，但通过精细分析是O(n)
        调整堆	        O(log n)	    每次调整最多比较树的高度次
        排序阶段	    O(n log n)	     执行n-1次调整，每次O(log n)
        总时间复杂度	O(n log n)	     最坏情况仍为O(n log n)
        空间复杂度	    O(1)	         原地排序

        注：建堆时间复杂度分析：
            看起来是O(n log n)（n/2个节点，每个调整O(log n)）
            但实际上大部分节点高度小，精确分析可得O(n)
            公式：∑(高度为h的节点数 × h) = O(n)


三、总结  
    1.总结：堆是一种重要的数据结构，堆排序是基于堆的高效排序算法。虽然在实际开发中，堆排序通常不是
        首选的通用排序算法（快速排序和Timsort通常更快），但堆的思想在以下场景中无可替代：

    2.堆排序的核心价值：
        最坏情况O(n log n)：有最坏情况性能保证
        原地排序：空间复杂度O(1)
        适合大数据：数据量大时表现稳定
        在线算法：可以处理数据流

    3.堆的主要应用：
        优先队列：快速获取最大/最小值
        Top K问题：高效找出前K个元素
        实时统计：中位数、百分位数等
        任务调度：按优先级执行任务
        图算法：Dijkstra算法、Prim算法
*/
#include <stdio.h>

// 交换数组中两个元素的值
void swap(int* data, int m, int n)
{
    int temp = data[m];
    data[m] = data[n];
    data[n] = temp;
}

// 核心函数————堆调整：从子树根节点开始不断向下调整(root为子树根节点编号，len为当前整棵树大小)
void adjust(int* data, int root, int len)
{
    int child;
    int temp = data[root];  // 保存当前root节点的值
    child = 2 * root;       // root的左孩子下标

    // child <= len表示存在左孩子节点
    while(child <= len)
    {
        // 如果有右孩子(即child < len)，且右孩子比左孩子大，则child表示右孩子下标
        if (child < len && data[child] < data[child+1])
        {
            child++;        // 右孩子下标
        }
        // 如果当前节点比其孩子大，则不需要调整(包括继续向下调整部分也不需要)
        if (temp > data[child])
        {
            break;
        }
        // 将子节点的值上移
        data[child/2] = data[child];

        // 继续向下调整
        child = child * 2; // child*2是child的左孩子
    }
    // 把原 root 的值放到最终位置
    data[child/2] = temp;
}

// 堆排序主函数
void heapSort(int* data, int len)
{
    // 1. 建堆过程：从最后一个非叶子节点(即len/2向下取整)开始向前遍历到根节点进行不断调整
    for (int i = len / 2; i > 0; i--)
    {
        adjust(data, i, len);
    }

    // 2. 排序过程：将堆顶最大值依次交换到数组末尾，并调整剩余部分为最大堆
    for(int i = len; i > 1; i--)
    {
        swap(data, 1, i);         // 将当前最大值（堆顶）移到末尾
        adjust(data, 1, i-1);     // 对剩余部分重新建堆
    }
}

int main(int argc, char const *argv[])
{
    // 注意：data[0]未使用，占位是为了从 data[1] 开始建堆
    int data[] = {-1, 47, 35, 60, 95, 77, 15, 28};
    int len = sizeof(data) / sizeof(data[0]);

    // 调用堆排序函数（不包含占位的 data[0]）
    heapSort(data, len-1);

    // 输出排序结果
    for(int i = 1; i < len; i++)
    {
        printf("%d ", data[i]); // 15 28 35 47 60 77 95
    }
    return 0;
}
