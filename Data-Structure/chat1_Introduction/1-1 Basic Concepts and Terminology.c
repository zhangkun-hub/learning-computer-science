/*
一、数据结构基本概念和术语：
    1.数据(data)：是对客观事物的符号表示，在计算机科学中是指所有能输入到计算机中并被计算机程序
                处理的符号的总称。
    2.数据元素(data element)：是数据的基本单位，在计算机程序中通常作为一个整体进行考虑和处理。
    3.数据对象(data object)：是性质相同的数据元素的集合，是数据的一个子集。
    4.数据结构(data structure)：是相互之间存在一种或多种特定关系的数据元素的集合。这种数据元素相互之间的关系称为结构(structure)。                                
        4类基本结构：
            (1)集合：结构中的数据元素之间除了“同属于一个集合”的关系外，别无其他关系。
            (2)线性结构：结构中的数据元素之间存在一个对一个的关系。
            (3)树形结构：结构中的数据元素之间存在一个对多个的关系。
            (4)图状结构或网状结构：结构中的数据元素之间存在多个对多个的关系。

            其中由于“集合”是数据元素之间关系极为松散的一种结构，因此也可用其他结构来表示它。


二、数据结构的形式定义：
    1.定义：数据结构是一个二元组：
            Data_Structure=(D,S)
        其中：D是数据元素的有限集，S是 D上关系的有限集。

    2.举例说明：计算机科学中，复数可取如下定义：复数是一种数据结构：
                Complex=(C,R)
        其中：C是含两个实数的集合{c1,c2}；R={P}，而P是定义在集合C上的一种关系{⟨c1,c2⟩}，
                其中⟨c1,c2⟩为有序偶，表示第一个元素c1是复数的实部，第二个元素c2是复数的虚部。


三、算法：
    1.算法的时间复杂度(也称渐近时间复杂度)（掌握）（具体见视频5）
        (1)程序运行的总时间：
            (a)决定因素：
                执行每条语句的耗时（不可测）
                每条语句的执行频率（可测）

            (b)具体解释：
                由于语句的执行要由源程序翻译成目标代码，目标代码经装配再执行，因此语句执行一次实际
            所需的具体时间是与机器的软、硬件环境（如机器速度、编译程序质量等）密切相关的。所以，所
            谓的算法分析并非实际执行所需时间，而是针对算法中语句的执行次数做出估计，从中得到算法
            执行时间的信息。

        (2)定义：一般算法中基本操作重复执行的次数是问题规模n的某个函数f(n)，算法的时间量度记作:
                                        T(n)=O(f(n))
                它表示随问题规模n的增大，算法执行时间的增长率和f(n)的增长率相同，称做算法的
                渐近时间复杂度(asymptotic time complexity)，简称时间复杂度。

        (3)语句的频度f(n)：指该语句重复执行的次数，它决定了算法的时间复杂度。
        
        (4)时间复杂度T(n)：
            (a)计算：并不按照数学严格求出重复执行次数，而是求出其数量级(具体见示例)
                原因：分析算法执行时间随输入数据规模增长而变化的趋势的量度，所以无需准确。

            (b)时间复杂度汇总(按时间复杂度由低到高排序)：
                常数阶O(1): 算法的执行时间不随输入数据规模 n的变化而变化。是最理想的效率。
                    示例：访问数组的某个元素(通过下标);在哈希表中插入/查找(平均情况)。

                对数阶O(logn): 执行时间随n呈对数增长。增长极为缓慢，效率极高。底数通常省略。
                    示例：二分查找(在有序数组中查找)；
                         平衡二叉搜索树(如AVL树、红黑树)的查找、插入、删除操作。

                平方根阶O(√n): 比O(log n)慢，但比O(n)快。不如前两者常见。
                    示例：判断一个数是否为质数（通过检查到√n的整数）。

                线性阶O(n): 执行时间与n成正比。数据量翻倍，时间也翻倍。这是许多高效算法的基线。
                    示例：遍历数组或链表；在无序数组中查找最大值/最小值。
                    
                线性对数阶O(n*log n): 比O(n)慢，但比O(n²)快得多。是许多高效排序算法的复杂度。
                    示例：快速排序、归并排序、堆排序的平均或最优情况。

                平方阶O(n²): 执行时间与n的平方成正比。当n较大时，性能急剧下降。
                    示例：冒泡排序、选择排序、插入排序（最坏或平均情况）；
                         用两层循环遍历一个二维数组（n * n矩阵）。

                立方阶O(n³): 通常出现在三层嵌套循环中。
                    示例：朴素矩阵乘法（两个n×n矩阵相乘）。
                
                指数阶O(2^n): 增长非常恐怖，n稍大（如超过30）算法就可能无法在可接受时间内完成。
                    示例：求解斐波那契数列的递归实现（未优化）；解决旅行商问题的暴力穷举法。
                
                阶乘阶O(n!): 增长最恐怖的时间复杂度，完全不具备可扩展性。
                    示例：排列问题，列出n个元素的所有全排列。

            (c)对于处理现代应用中的大规模数据，追求O(n)或O(n*log n)及更优的时间复杂度，
                是算法高效的关键标志，而O(n²)及以上的算法一般需要进行优化处理。


    2.算法的空间复杂度（了解即可）：即算法所存储空间(内存)的量度。
        在内存充足的时代，我们通常更“烧内存”来“买时间”，以提升速度，即用空间换时间的算法。
*/
#include<stdio.h>

int main()
{
    int x = 0;
    int s;
    int n = 5;  
    int y;

    // 示例1 常数阶时间复杂度
    printf("------------- 示例1 --------------\n");
    x++;   // 频度为1
    s = 0; // 频度为1
    // f(n) = 1+1 = 2，故T(n) = O(1)，为常数阶时间复杂度


    // 示例2 线性阶时间复杂度
    printf("------------- 示例2 --------------\n");
    for(int i = 0; i < n; i++) // 频度为n+1，因为循环结束还需要进行判断，也就是执行一次该语句
    {
        x++;        // 频度为n
        s = 0;      // 频度为n
    }
    // f(n) = (n+1) + n + n = 3n + 1，故T(n) = O(n)，为线性阶时间复杂度


    // 示例3 平方阶时间复杂度
    printf("------------- 示例3 --------------\n");
    x = 0;         // 频度为1
    y = 0;         // 频度为1
    for(int k = 1; k <= n; k++)     // 频度为n+1
    {
        x++;                        // 频度为n
    }
    for(int i = 1; i <= n; i++)     // 频度为n+1
    {
        for(int j = 1; j <= n; j++) // 频度为n*(n+1)
        {
            y++;                    // 频度为n^2
        }
    }
    // f(n)=1+1+(n+1)+n+(n+1)+n(n+1)+n^2=2n^2+4n+4，故T(n) = O(n^2)，为平方阶时间复杂度


    // 示例4 立方阶时间复杂度(以下均忽略循环中for语句多执行的一次)
    printf("------------- 示例4 --------------\n");
    x = 1;    // 频度为1
    for(int k = 1; k <= n; k++)     // 频度为n
    {
        for(int i = 1; i <= k; i++)     // 频度为(1+2+...+n)=n(n+1)/2
        {
            for(int j = 1; j <= i; j++) // 频度为n(n+1)/2
            {
                x++;   // 频度为1+(1+2)+(1+2+3)+...+(1+2+3+...+n)=[n(n+1)(n+2)]/6
            }
        }
    }
    // T(n) = O(n^3)，为立方阶时间复杂度


    // 示例5 对数阶时间复杂度
    printf("------------- 示例5 --------------\n");
    for(int i = 1; i <= n; i = i * 2)     // 循环次数：1       2      3      4      t
    {                                     // i的取值：1=2^0  2=2^1  4=2^2  8=2^3  2^(t-1)
        x++;
        s = 0;       // 由循环结束条件可知：2^(t-1)=n -> t-1=lgn/lg2 -> t=lgn/lg2+1
    }
    // T(n) = O(lgn)，为对数阶时间复杂度


    // 示例6 1/2阶时间复杂度
    printf("------------- 示例6 --------------\n");
    int i = 0;                              // 循环次数:1   2   3   4      t
    int sum = 0;                            //   i取值：1   2   3   4      t
    n = 5;                                  // sum取值：1   3   6   10  t(t+1)/2
    while(sum < n) sum += ++i;   // 由循环结束条件可知：t(t+1)/2=n -> t(t+1)=2n -> t^2+t=2n
    // T(n) = O(n^(1/2))，为1/2阶时间复杂度


    // 示例7 408考研真题
    printf("------------- 示例7 --------------\n");
    for(int i = 1; i < n; i *= 2)   // 外层循环次数： 1    2    3    4     t
    {                               //     i的取值：2^0  2^1  2^2  2^3  2^(t-1)
        for(int j = 0; j < i; j++)  // 内层循环次数：2^0  2^1  2^2  2^3  2^(t-1)
        {
            sum++;    // 由外层循环结束条件可知：t=lgn/lg2+1。于是内层循环总次数即该算法频度：
        }             // 2^0+2^1+2^2+...+2^(t-1)=1+2+4+...+2^(lgn/lg2)=n-1
    }
    // T(n) = O(n)，为线性阶时间复杂度


    return 0;
}