"""
一、序列：是一个用于储存多个值的连续空间，每个值都对应一个整数的编号，称为索引。

二、特点：
    1.有序性​：元素按照特定顺序排列；
    2.可索引：可以通过数字索引访问元素（从0开始）；
    3.可切片：可以获取序列的一部分；
    4.可迭代​：可以使用循环遍历；
    5.有长度：可以使用len()获取元素个数。

二、种类：字符串、列表、元组、集合和字典。
    1.有序序列(字符串、列表和元组)：元素按照插入顺序排列，可以通过索引访问
        特点：
            (1)保持元素的插入顺序;
            (2)可通过索引（数字位置）访问元素;
            (3)支持切片操作;
            (4)可比较(按元素顺序比较)。
    2.无序序列(集合和字典)：元素不保持插入顺序，不能通过索引访问
        特点：
            (1)不保证元素的存储顺序;
            (2)不能通过数字索引访问;
            (3)通常基于哈希表实现;
            (4)用于去重和快速成员检查。
    2.可变序列(列表、集合和字典)：创建后可以修改其内容的序列,修改后内存地址并不改变(因为在原地修改)
        特点：
            (1)可以添加、删除、修改元素;
            (2)支持原地修改操作;
            (3)通常是可哈希的（但可变对象本身不可哈希）。
    3.不可变序列(字符串和元组。注:整数、浮点数等都是不可变数据类型)：创建后不能修改其内容的序列
        特点：
            (1)创建后内容固定不变;
            (2)任何"修改"都会创建新对象;
            (3)通常可哈希，可作为字典的键;
            (4)线程安全。

四、索引(用于访问等操作)
    1.正向递增索引：从左向右依次增加，左边第一个元素编号为0；
    2.反向递减索引：从右向左依次减小，右边第一个元素编号为-1。

五、序列的切片操作：对于序列x，其x[a:b:c]与range(a,b,c)的abc含义完全一致
        具体看见6-1节内容
"""

### 示例1 使用索引检索字符串中的元素
print("--------------------- 示例1 -------------------------")
#正向递增
s='helloworld'
for i in range(0,len(s)):
    print(i,s[i],end='\t\t')
print('\n------------------')
#逆向递减索引
for i in range(-len(s),0):
    print(i,s[i],end='\t\t')

print('\n',s[9],s[-1])


### 示例2 序列的切片操作
print("--------------------- 示例2 -------------------------")
s = 'HelloWorld'
# 切片操作
s1 = s[0:5:2]  # 索引从0开始，到5结束(不包含5)，步长为2
print(s1)
print('-'*20)
# 省略了开始位置，start默认从0开始
print(s[:5:1])
print('-'*20)
# 省略步长则默认步长为1
print(s[:5:])
print(s[:5]) #与10代码相同
print('-'*20)
# 省略结束位置，默认到结尾并包含最后一个元素
print(s[0::1])

print(s[5::])
print(s[5:]) # 12行代码与13行代码功能相同
print('-'*20)
# 省略开始与结束位置，只写步长
print(s[::2])
print(s[:2]) # 与16行代码有区别，表示步长为1，从0开始长度为2
#步长为负数,则步长逆向递减索引进行切片输出
print('-'*20)
print(s[::-1])
print(s[-1:-11:-1])


### 示例3 序列的相加和相乘操作
print("--------------------- 示例3 -------------------------")
# 序列的相加操作
s='Hello'
s2='World'
print(s+s2) # HelloWorld （产生一个新的字符串序列）
# 序列的相乘操作
print(s*5)
print('-'*20)


### 示例4 序列的相关操作和函数的使用
print("--------------------- 示例4 -------------------------")
s='helloworld'
print(f'序列s = {s}')

# in的使用
print('元素e在序列s中存在吗？',('e' in s))
print('元素v在序列s中存在吗？',('v' in s))

# not in的使用
print('元素e在序列s中不存在吗？',('e' not in s))
print('元素v在序列s中不存在吗？',('v' not in s))

# 内置函数的使用
print('序列s的长度(元素个数)：',len(s))
print('序列s中元素的最大值：',max(s)) # 通过元素的ASCII值去计算
print('序列s中元素的最小值：',min(s)) # 通过元素的ASCII值去计算

# 序列对象的方法(方法：使用对象名称通过打点调用的称为方法,比如下面s.index(),而前面的len()都是函数)
print('序列s中第一次出现元素l的位置：',s.index('l')) # 注意如果元素在序列中不存在则会报错
print('序列s中出现l的总次数：',s.count('l'))