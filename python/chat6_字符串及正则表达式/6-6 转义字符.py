r"""
一、转义字符：转义字符是以反斜杠\开头的特殊字符序列，表示在字符串中难以直接输入或有特殊含义的字符。

二、转义字符种类：
    1.常用转义字符列表(不止这些)：
        转义字符    功能描述                 示例                    输出结果
        -------    ----------------        ------------------      --------------------
        \          一整行代码的续行符        一行代码\下一行代码       一行代码(即两行代码由\连接成一行代码)
        \\         反斜杠字符               "C:\\Users\\Name"       C:\Users\Name
        \'         单引号                   'It\'s me'              It's me
        \"         双引号                   "He said: \"Hello\""    He said: "Hello"
        \n         换行符                   "Line 1\nLine 2"        两行文本
        \r         回车符                   "Hello\rWorld"          World（覆盖效果）
        \t         水平制表符(Tab)          "Col1\tCol2"            用制表符分隔的两列
        \b         退格符(删除前一个字符)    "123\b\b456"            1456（退格删除）
        \f         换页符(用于打印机)        "Page1\fPage2"          分页效果
        \a         响铃(系统提示音)          print("\a")             系统发出提示音
        \v         垂直制表符                "Top\vBottom"           垂直对齐效果
        \0         空字符(null)             "A\0B"                  包含空字符的字符串

\t详细解释：水平制表符,根据前面字母长度在后面补空格,让整体长度为8或8的倍数,最少补1个,最多补8个；
\r详细解释：回车符，将光标移动到行首，后续内容会覆盖行首开始的内容。        

    2.特殊表示法(不止这些)：
        转义字符      功能描述            示例                    输出结果
        ---------    ----------------   ------------------      --------------------    
        \ooo         八进制值字符         "\101"                  A（ASCII 65）
        \xhh         十六进制值字符       "\x41"                  A（十六进制 41）
        \N{name}     Unicode名称字符     "\N{EURO SIGN}"         €
        \uhhhh       16位Unicode字符     "\u20AC"                €（欧元符号）
        \Uhhhhhhhh   32位Unicode字符     "\U0001F604"            😄（笑脸表情）
            
三、原始字符串(忽略转义)：在字符串前加 r 或 R 创建原始字符串，转义字符会被当作普通字符。
    1.形式：原始字符串 = r'字符串内容'

    2.使用场景：
        (1)始终对正则表达式使用原始字符串,避免python的转义字符与正则表达式的元字符和转义字符冲突；
        (2)处理Windows路径时使用原始字符串，使代码更清晰；
        (3)当需要大量反斜杠时使用原始字符串，如LaTeX表达式、转义序列等；
        (4)注意原始字符串的结束反斜杠问题，避免语法错误；
        (5)原始字符串与格式化字符串结合（rf）可以创建动态的原始字符串。
"""
### 示例1 常用转义字符的使用
print("--------------------- 示例1 -------------------------")
# \n的使用
print('北京\n欢迎你') # 遇到\n换行，可以连续换多行,此处\n便是转义字符
print('北\n京\n欢\n迎\n您')
print()

# \t、\r、\b的使用
print('北京\t欢迎你') # \t的空格大小取决于前面字符的长度，一个制表位填满再去填下一个。
print('hello\toooo') # hello是5个字符，一个制表位是8个字符，由8-5=3可知空位是3个

print("123456\rABC")  # 输出: ABC456

print("Hello\b\b\b世界")  # 输出: He世界，即Hello后退3格，从第3个位置开始输出"世界"

# \'、\"、\\的使用
print('It\'s a beautiful day.') # 在单引号字符串中使用单引号(使用双引号则无需转义)
print("He said, \"Hello World!\"") # 在双引号字符串中使用双引号(使用单引号则无需转义)
print('She replied, \"It\'s nice to see you!"') # 混合使用
print("两个反斜杠: \\\\")  # 输出: 两个反斜杠: \\
print()


### 示例2 其他转义字符的使用
print("--------------------- 示例2 -------------------------")
# 1. 特殊字符示例
print("\n1. 特殊字符:")
# 响铃符（某些终端可能不响）
print("\a")  # 可能会听到系统提示音

# 2. 八进制和十六进制表示
print("\n2. 数值表示:")
print("八进制 \\101: ", "\101")  # 输出: A
print("十六进制 \\x41: ", "\x41")  # 输出: A

# 3. Unicode 字符
print("\n3. Unicode 字符:")
print("欧元符号: \u20AC")  # €
print("欧元符号(名称): \N{EURO SIGN}")  # €
print("笑脸: \U0001F604")  # 😄

# 4. 多行字符串
print("\n4. 多行字符串:")
multi_line = """第一行
第二行
\t第三行（带缩进）"""
print(multi_line)


### 示例3 转义字符在字符串处理中的应用
print("--------------------- 示例3 -------------------------")
# 1. 转义字符在字符串处理中的应用
print("\n1. 字符串处理应用:")
# 格式化表格输出
print("姓名\t年龄\t城市")
print("----\t----\t----")
print("张三\t25\t北京")
print("李四\t30\t上海")

# 2. 包含多种转义字符的字符串
complex_string = "列1\t列2\t列3\n----\t----\t----\nA\tB\tC"
print(f"\n2. 复杂字符串:\n{complex_string}")
print()


### 示例4 原始字符串（忽略转义）
print("--------------------- 示例4 -------------------------")
print("原始字符串:")
raw_string = r"C:\Users\Name\n不再换行"
print(raw_string)  # 输出: C:\Users\Name\n不再换行