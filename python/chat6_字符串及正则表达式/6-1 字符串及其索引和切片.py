"""
一、字符串：字符串是Python中用来表示文本数据的数据类型，是由字符组成的不可变序列。

二、字符串的创建方式：
    直接使用' '(单引号)、" "(双引号)、""" """(三引号)创建

三、删除方式：del 字符串名

四、字符串的基本特性：
    1.不可变：创建后不能修改
    2.有序：字符有固定位置
    3.可迭代：可以遍历每个字符
    4.支持索引和切片：像列表一样访问
    5.可哈希：可以作为字典键

五、高级特性：
    1.编码支持：默认UTF-8，支持多语言
    2.转义字符：\n（换行）、\t（制表）、\\（反斜杠）
    3.原始字符串：r"路径\名称"忽略转义
    4.格式化：多种字符串格式化方式
    5.方法丰富：超过40个内置方法

六、作用：
    1.文本处理：文件读写、数据处理
    2.用户交互：输入输出、命令行界面
    3.数据表示：JSON、XML、CSV等格式
    4.网络通信：HTTP请求、API响应
    5.模板生成：HTML、邮件、报告
    6.日志记录：调试和监控信息
    7.配置管理：配置文件、环境变量

七、字符串的索引和切片：
    1.索引：
        字符串:   H  e  l  l  o
        正向索引: 0  1  2  3  4

        字符串:   H  e  l  l  o
        负向索引: -5 -4 -3 -2 -1

    2.切片语法结构：字符串[开始索引:结束索引:步长]
            具体下面示例1，特别注意负向索引的切片与负向步长的切片
        注意：
            (1)步长为正时，开始位置必须在结束位置之前，否则结果为空字符串(见64行代码)；
            (2)步长为负时，开始位置必须在结束位置之后，否则结果为空字符串(见74行代码)；
            (2)字符串的反转操作可以通过[::-1]实现

八、常用的字符串操作：+、*、in的作用直接见示例2
"""
### 示例1 字符串的索引和切片
print("--------------------- 示例1 -------------------------")
s='HELLO,WORLD'
# 索引示例
print(s[0],s[-10])     # H E (序号0和序号-10表示的是同一个字符，具体看课程P15)
print('北京欢迎你'[4])  # 你 (获取字符串中索引为4的字符)
print('北京欢迎你'[-1]) # 你
print()

# 切片操作
print(s[2:7])    # LLO,W  (切片从2开始到7结束不包含7)
print(s[-8:-3])  # LO,WO  (根据序列HELLO,WORLD的序号对应法则，-8对应3，-3对应8，即[3:8])
print(s[6:-2])   # WOR  (根据序列HELLO,WORLD的序号对应法则，-2对应9，即[6:9])
print(s[:5])     # HELLO  (默认从0开始不包含5)
print(s[5:])     # ,WORLD  (默认是切到字符串的结尾)
print(s[1:1])    # 结果为空字符串
print()

# 步长的调整
print(s[::2])      # HLOWRD  
print(s[3:9:2])    # L,O
print(s[::-1])     # DLROW,OLLEH  (相当于字符串的反转操作)
print(s[-1:-7:-2]) # DRW
print(s[-1:4:-2])  # DRW  (4对应-7，于是与上面结果完全一致)
print(s[10:-7:-2]) # DRW  (10对应-1，于是与上面结果完全一致)
print(s[-7:-1:-1]) # 结果为空字符串

### 示例2 常用的字符串操作：+、*、in。
print("--------------------- 示例2 -------------------------")
x='2022'
y='北京冬奥会'
print(x+y) # 连接两个字符
print(x*10) # 对x这个字符串的内容复制10次
print(10*x)
print('北京'in y) # 判断"北京"是否是y字符串的字串，是则为True,否则为False
print('上海'in y)
z='北的京冬奥会'
print('北京'in z) # False
