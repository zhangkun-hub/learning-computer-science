"""
程序调试：
一、设置断点(通常是设置在函数定义处、然后是循环处)：
    设置断点的三种方法：
    1.在行号左侧单击，出现红点
    2.右键 → "添加断点"
    3.快捷键：F9 (切换断点)    

二、进入调试窗口(快捷键为F5)

三、调试界面详解
    1.调试工具栏
         按钮            快捷键                         功能 
        ------       --------------      ---------------------------------
        ▶️继续            F5              跳过当前断点，直接执行到下一个断点 
        ⤵️逐过程          F10                  执行当前行，不进入函数 
        ⬇️单步进入        F11                   进入当前行调用的函数 
        ⬆️单步跳出     Shift+F11                    跳出当前函数 
        🔄重启       Ctrl+Shift+F5                 重新开始调试 
        ⏹️停止         Shift+F5                      停止调试 

    2.调试侧边栏面板
        (1)VARIABLES (变量面板)
            - Local: 当前函数的局部变量
            - Global: 全局变量
            - Special Variables: 特殊变量 (如 __name__)

        (2)WATCH (监视面板)
            可以添加表达式监视。示例：添加 len(data)或 total * 2

        (3)CALL STACK (调用堆栈)
            显示函数调用链，可以点击跳转到不同函数
        
        (4)BREAKPOINTS (断点面板)
            查看和管理所有断点
            启用/禁用断点
            设置断点条件
"""
### 示例1 正常循环
print("--------------------- 示例1 -------------------------")
j = 1
while j < 10:
    print(j)
    j+=1


### 示例2 死循环
print("--------------------- 示例2 -------------------------")
