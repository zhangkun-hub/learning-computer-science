"""
一、数据格式：
    1.JSON格式：
        (1)定义：是一种轻量级的数据交换格式。它源于 JavaScript，但现在已成为一种独立于语言的格式。
      
        (2)特点：
            (a)它的基本结构是键值对(key: value)的集合构成的字符串，例如：
                    '{"name":"admin","age":18}'
                    '[{"name":"admin","age":18},{"name":"root","age":16}]'  
            (b)可以在各种计算机语言中传递数据(相当于中转站)。
            (c)因为JSON格式跟python中字典高度切合(由基本结构可知)，所以在python中可以无缝切换。
      
        (3)优点：
            (a)结构化程度高，可读性好(对机器和开发者)：清晰的层次结构使得数据关系一目了然，
                  非常易于理解和调试；
            (b)支持复杂数据结构：可以轻松表示嵌套的对象和数组，非常适合配置文件和 API 数据传输；
            (c)数据类型丰富：自动区分字符串、数字、布尔值等，无需额外解析；
            (d)广泛的生态支持：几乎所有编程语言都有成熟、高效的 JSON 解析和生成库。

        (4)缺点：
            (a)文件体积相对较大：由于包含大量的括号、引号和键名等冗余字符，文件尺寸通常比 CSV 大；
            (b)语法严格：必须严格遵守语法规则（如逗号、引号、括号必须配对），否则解析会失败；
            (c)不适合人类直接编辑大量数据：虽然可读，但编辑大型 JSON 文件（尤其是手动）容易出错。
      
        (5)主要用途：Web API、配置文件(如 package.json、tsconfig.json)、
                    存储有复杂关系的结构化数据。
                
    2.CSV格式：
        (1)定义：是用纯文本形式存储表格数据(数字和文本)的格式。

        (2)核心思想:每一行代表表格中的一行记录,每一行各个字段(列)用特定的分隔符(通常逗号)隔开。

        (3)优点：
            (a)非常紧凑，文件小：只存储数据本身和必要的分隔符，空间利用率极高；
            (b)易于生成和解析：格式简单，无论是用代码生成还是用文本编辑器、Excel等打开都非常方便；
            (c)与电子表格软件兼容性极佳：可以直接被Microsoft Excel、Google Sheets、Numbers等
                        软件导入和导出，进行可视化操作；
            (d)处理大量平面数据时效率高：对于简单的、无嵌套的表格数据，流式读取和处理非常高效。

        (4)缺点：
            (a)无法直接表示复杂数据结构：难以表示嵌套数据，虽然可以变通，但会很别扭；
            (b)无标准数据类型：所有值都被视为字符串,需要程序在读取时根据上下文进行类型转换
                        (例如,将"30"转为数字30,将"TRUE"转为布尔值 true)；
            (c)容易出现格式问题：如果数据内包含分隔符、换行符或引号，需要额外的转义规则
                        (如用引号包裹)，处理不当容易导致解析错误；
            (d)无模式定义：文件本身不包含列的数据类型、约束等信息，需要额外文档或约定。

        (5)主要用途：数据导出/导入、数据交换、科学数据记录、简单的平面数据存储。    
            
    3.文本格式(.txt)：
        (1)定义：文本文件是最通用、最基础的文件格式。
    
        (2)特点：它不包含任何格式信息（如字体、颜色），只存储纯粹的字符序列。

        (3)优点：
            (a)极度灵活，无任何限制：你可以存储任何你想存储的文本信息，格式完全自定义；
            (b)通用性最强：任何设备、任何操作系统上的任何一个文本编辑器都能打开和编辑它；
            (c)简单直观：创建和查看都非常容易，是存储非结构化文本信息的首选。

        (4)缺点：
            (a)非结构化：这是最大的缺点。程序很难自动解析和理解其内容，
                需要编写复杂的、特定的解析逻辑(例如，用正则表达式匹配日志)；
            (b)无法直接存储复杂数据​： 要表示结构化或半结构化数据，需要自己发明一套规则，
                这通常比使用 JSON 或 CSV 更麻烦且容易出错；
            (c)无元数据：文件本身不包含任何关于其编码(如UTF-8,GBK)的信息，打开时可能会出现乱码。

        (5)主要用途：日志文件、README 文档、源代码、小说等任何不需要复杂结构的纯文本内容。

        
二、JSON数据格式的在python中的使用：
    1.导入json模块。

    2.通过data_j = json.dumps(data_p)方法把python数据data_p转换成json数据data_j。

    3.通过data_p = json.loads(data_j)方法把json数据data_j转换成python数据data_p。
"""
### 示例1 JSON数据和Python数据的相互转换
print("--------------------- 示例1 -------------------------")
### 导入json模块
import json

### 建立python数据，并转换成json数据
data = [{"name":"张大山","age":11}, {"name":"王大锤","age":13}, {"name":"赵小虎","age":16}]
json_str = json.dumps(data, ensure_ascii = False)  
# 注：ensure_ascii=False表示不用ASCII码转换而直接输出内容，这样可以输出中文而不是Unicode字符了

print(type(data))      # <class 'list'>
print(type(json_str))  # <class 'str'>
print(json_str)

### 将json字符串转换成pyhon数据
s = '[{"name":"张大山","age":11}, {"name":"王大锤","age":13}, {"name":"赵小虎","age":16}]'
l = json.loads(s)
print(type(s))    # <class 'str'>
print(type(l))    # <class 'list'>
print(l)       

