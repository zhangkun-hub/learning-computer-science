### 示例1 算术运算符的使用
print("--------------------- 示例1 -------------------------")
print('加法：',1+1)
print('减法：',1-1)
print('乘法：',2*3)
print('除法：',10/2) # 5.0，是一个浮点数float
print('整除：',10//3) # 3,是一个整数int
print('取余',10%3)
print('幂运算',2**4) # 2*2*2*2
# 算术运算符优先级跟数学一致

### 示例2 赋值运算符的使用
print("--------------------- 示例2 -------------------------")
x=20 # 直接将20赋值给左侧的变量x
y=10
x=x+y # 将x+y的和赋值给x,x值为30
print(x)
x+=y # 40,相当于x=x+y
print(x)
x-=y # 相当于x=x-y
print(x)
x*=y # 相当于x=x*y
print(x)
x/=y #相当于x=x/y
print(x)
x%=2 #相当于x=x%2
print(x)
z=3
y//=z # 相当于y=y//z
print(y)
y**=2 # 相当于y=y**2
print(y)

#python支持链式赋值
a=b=c=100 # 相当于a=100,b=100,c=100
print(a,b,c)

# python支持系列解包赋值
a,b=10,20 # 相当于执行了a=10,b=20
print(a,b)

print('---如何交换两个变量的值呢？---')
a,b=b,a # 将b的值赋给a,将a的值赋给b
print(a,b)

