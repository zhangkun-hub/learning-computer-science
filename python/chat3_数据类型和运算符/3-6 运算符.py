### 示例4 逻辑运算符的使用(与and、或or、非not)
print("--------------------- 示例4 -------------------------")
print(True and True)
print(True and False)
print(False and False)
print(False and True)
print()

print(8>7 and 6>5)
print(8<7 and 10/0) # 10/0没有运算，因为当第一个表达式的结果为False，直接得结果，不会计算and右侧的表达式了
# print(10/0 and 8<7) # ZeroDivisionError: division by zero
print()

print(True or True)
print(True or False)
print(False or False)
print(False or True)
print()

print(8>7 or 10/0) # 左侧表达式结果为Ture时，or的右侧表达式根本不执行运算符
print()

print(not True)
print(not False)
print(not(8>7))

### 示例5 位运算符的使用
print("--------------------- 示例5 -------------------------")
# 位运算符是把数字看作二进制数来进行各种操作运算(具体见课程P23)
print('按位与运算:',12&8) # 8
print('按位或运算:',4|8)  # 12
print('按位异或运算:',31^9) # 22
print('按位取反运算:',~123) # -124
print('左移位运算:',4<<3) # 表示4转换成二进制再向左移动3位后再转换成十进制
print('右移位运算:',8>>2) # 表示8转换成二进制再向右移动2位后再转换成十进制