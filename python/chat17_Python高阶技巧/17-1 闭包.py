"""
闭包
一、引入背景：一般函数内部无法访问外部函数的局部变量（只能读取全局变量和自身局部变量），但全局变量
            具有牵一发而动全身的风险，为了解决这个问题，从而引入了闭包的内容。

二、定义：在函数嵌套前提下，内部函数使用了外部函数的变量，并且外部函数返回了内部函数，我们把这个
        使用外部函数变量的内部函数称为闭包。

三、语法：
    def outer_func(x):          # 外部函数，其中参数x是外部函数的局部变量而非全局变量
        def inner_func(y):      # 内部函数（嵌套函数）
            return x + y        # 访问外部函数的变量x
        return inner_func       # 外部函数的返回值，返回内部函数（注意：返回函数不加括号）

    # 创建闭包
    closure = outer_func(10)    # closure现在是一个闭包，记住了x=10
    result = closure(5)         # 调用闭包，输出15
    print(result)               # 15


三、在闭包中修改外部函数变量的值操作：nonlocal关键字修饰。
    在内部函数中使用nonlocal关键字修饰外部函数的变量，才可在内部函数中修改它。  

四、核心特征：
    1.必须有嵌套函数（函数内定义函数）。
    2.内部函数必须引用外部函数的变量。
    3.外部函数必须返回内部函数。

五、作用：
    1.数据隐藏：将变量隐藏在函数作用域内，避免全局命名空间污染。
    2.状态保持：函数多次调用间可以保持状态（类似简单对象）。
    3.实现装饰器：装饰器的核心机制就是闭包。
    4.函数工厂：动态创建功能相似的函数。
    5.延迟计算：可以延迟变量的计算。


六、优缺点：
    1.优点：
        (1)无需定义全局变量即可实现通过函数，持续的访问、修改某个值。
        (2)闭包使用的变量所用于在函数内，难以被错误的调用修改。

    2.缺点：由于内部函数持续引用外部函数的值，所以这会导致这一部分内存空间不被释放，一直占用内存。
"""
### 示例1 简单闭包
print("--------------------- 示例1 -------------------------")
### 外部函数
def outer(logo):

    ## 内部函数（嵌套函数）
    def inner(msg):
        print(f"<{logo}>{msg}<{logo}>")  # 访问外部函数的变量logo

    ## 外部函数的返回值，返回内部函数（注意：返回函数不加括号）
    return inner    

### 创建闭包
fn1 = outer("黑马程序员") # fn1就是闭包，记住了logo="黑马程序员"

### 调用闭包
fn1("大家好")  # <黑马程序员>大家好<黑马程序员>
fn1("你好")    # <黑马程序员>你好<黑马程序员>


### 示例2 可修改外部函数变量的闭包
print("--------------------- 示例2 -------------------------")
### 外部函数
def outer2(num1):

    ## 内部函数（嵌套函数）
    def inner2(num2):
        nonlocal num1  # 通过关键字nonlocal对外部函数变量num1修饰，从而可以在内部函数中进行修改
        num1 += num2   # 对外部函数变量num1值的修改
        print(num1)

    ## 外部函数的返回值，返回内部函数（注意：返回函数不加括号）
    return inner2      

### 构建闭包
fn2 = outer2(10)
fn2(10)   # 20
fn2(10)   # 30（因为nonlocal的作用，导致num1可以不断被修改）
fn2(10)   # 40（因为nonlocal的作用，导致num1可以不断被修改）


### 示例3 使用闭包实现ATM功能
print("--------------------- 示例3 -------------------------")
def account_create(initial_amount=0):

    def atm(num, deposit=True):
        nonlocal initial_amount
        if deposit:
            initial_amount += num
            print(f"存款：+{num}，账户余额{initial_amount}")
        else:
            initial_amount -= num
            print(f"取款：-{num}，账户余额{initial_amount}")

    return atm

atm = account_create()
atm(100)               # 存款：+100，账户余额100
atm(200)               # 存款：+200，账户余额300
atm(50, deposit=False) # 取款：-50，账户余额250
    