### 示例8 使用f-string 格式化
"""
特点：允许在字符串中直接嵌入变量或表达式。
具体操作：用{}表示需要嵌入的内容，然后通过前缀f''来告诉Python在字符串中查找 {} 内的表达式
并将它们的值动态插入到字符串中，其中大括号内甚至可以写简单计算或函数调用
"""
print("--------------------- 示例8 -------------------------")
name = "李四"
age = 28
print(f"姓名: {name}, 年龄: {age}")
print(f'数学运算：{x}+{y}={x+y}，这是加法运算')

# 还可以在{}内添加格式说明符，例如控制小数位数：
pi = 3.1415926
print(f'PI rounded: {pi:.2f}')  # 输出：PI rounded: 3.14
# pi:.2f为格式说明符的起始符号;.2f为格式规则。
# 其中：.为后面要指定小数部分的格式；2为保留两位小数；f表示以​浮点数输出(e/E则为科学计数法输出)
