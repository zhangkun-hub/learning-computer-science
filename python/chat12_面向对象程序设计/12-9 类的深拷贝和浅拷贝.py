"""
注：赋值、浅拷贝和深拷贝从内存空间角度更深刻的理解见示例4

一、赋值：为现有对象创建一个新的引用（别名）。多个变量名指向内存中的同一个对象。
    1.特点：
        (1)修改任意一个变量(无论是修改整个对象还是对象的内部元素)，所有关联的变量都会看到这个变化。
        (2)操作是瞬间完成的，不涉及数据复制。

    2.优缺点：
        优点：效率极高，不占用额外内存。
        缺点：数据耦合度高，一个地方的修改可能无意中影响程序其他部分，容易引入难以调试的错误。

    3.作用与应用场景：
        作用：为对象起一个更短或更具语境化的别名。
        场景：当你想让多个标签指向同一个对象，且明确希望它们完全同步变化时使用。
                （例如，函数内希望直接修改传入的可变参数）。

                
二、浅拷贝：创建一个新的容器对象，但只拷贝一层，其子对象内容不拷贝，与原对象共用同一子对象。
    1.操作：调用copy模块，用b = copy.copy(a)实现b对a的浅拷贝。

    2.特点：
        (1)对顶层元素（如替换整个列表、字符串）的修改是独立的。
        (2)对嵌套的可变对象内部的修改，依然会影响到原对象，因为它们共享同一个子对象的引用。

    3.优缺点：
        优点：比深拷贝快，内存开销小。在顶层结构上实现了独立。
        缺点：无法实现嵌套可变对象的完全独立。

    4.作用与应用场景：
        作用：快速复制一个对象的结构，当顶层操作需要独立，但可以接受或不关心子对象共享时。
        场景：(1)复制一个配置字典的框架，但内部的具体数据对象(如已打开的文件、数据库连接)希望共享；
              (2)复制一个包含不可变元素（如数字、字符串、元组）的列表。

    
三、深拷贝：创建一个完全独立的对象，并给其完全独立的内存空间，然后递归地复制原对象及其所有子对象。
    1.操作：调用copy模块，用b = copy.deepcopy(a)实现b对a的深拷贝。

    2.特点：两个对象完全脱钩。修改任何一个对象（无论哪一层），都不会影响另一个。

    3.优缺点：
        优点：数据完全独立，最安全，不会产生意外的副作用。
        缺点：(1)对复杂对象（嵌套层次深、数据量大）进行拷贝时，速度最慢，内存开销最大。
              (2)可能引发循环引用问题（copy.deepcopy能处理大部分循环引用，但极端情况需注意）。

    4.作用与应用场景：
        作用：创建对象的完整副本，确保后续任何修改的独立性。
        场景：(1)需要修改一个复杂、嵌套的配置或数据结构的副本，而不想破坏原始数据；
              (2)在多线程或需要状态隔离的环境中使用数据副本。

"""
### 示例1 赋值
print("--------------------- 示例1 -------------------------")
a = [1, 2, [3, 4]]  # 原始列表，包含一个嵌套的子列表
b = a               # 赋值操作
b.append(5)         # 通过b修改列表
print(a)            # 输出：[1, 2, [3, 4], 5]  a也被改变了
b[2].append(99)     # 通过b修改嵌套的子列表
print(a)            # 输出：[1, 2, [3, 4, 99], 5]  a的子列表也被改变了


### 示例2 浅拷贝
print("--------------------- 示例2 -------------------------")
import copy
a = [1, 2, [3, 4]]
b = copy.copy(a)    # 或 b = a.copy() 或 b = a[:] （对于列表）
b.append(5)         # 修改顶层：添加新元素
print(a)            # 输出：[1, 2, [3, 4]]  a不受影响
b[2].append(99)     # 修改嵌套的可变对象
print(a)            # 输出：[1, 2, [3, 4, 99]]  a的子列表被改变了！


### 示例3 深拷贝
print("--------------------- 示例3 -------------------------")
import copy
a = [1, 2, [3, 4]]
b = copy.deepcopy(a)
b.append(5)
print(a)            # 输出：[1, 2, [3, 4]]  a不受影响
b[2].append(99)
print(a)            # 输出：[1, 2, [3, 4]]  a的子列表也不受影响！
print(b)            # 输出：[1, 2, [3, 4, 99], 5]


### 示例4 从内存空间的角度理解赋值、浅拷贝与深拷贝区别
print("--------------------- 示例4 -------------------------")
class CPU:
    pass

class Disk:
    pass

class Computer:
    # 计算机由CPU和硬盘组成
    def __init__(self, cpu, disk):
        self.cpu = cpu
        self.disk = disk

cpu = CPU()   # 创建一个CPU对象，从而占用一个内存空间(假设内存地址为A)
disk = Disk() # 创建一个硬盘对象，从而占用一个内存空间(假设内存地址为B)

# 创建一个计算机对象，从而占用一个内存空间(假设内存地址为C)
com = Computer(cpu, disk)  # 其中cpu与disk是com的子对象，其内存地址指向是A和B

### 一、赋值操作下，没有创建新的对象与子对象(只是名字不同而已)，内存地址保持不变
com1 = com
print(com, com.cpu, com.disk)
print(com1, com1.cpu, com1.disk)
print()

### 二、浅拷贝操作下，会创建对象占用新的内存空间(假设地址为D)，但没有创建新的子对象(内存地址仍然是A和B)
com2 = copy.copy(com)
print(com, com.cpu, com.disk)
print(com2, com2.cpu, com2.disk)
print()

### 三、深拷贝操作下，会创建新的对象与子对象占用新的内存空间(新的内存地址假设为E、F、G)
com3 = copy.deepcopy(com)
print(com, com.cpu, com.disk)
print(com3, com3.cpu, com3.disk)
